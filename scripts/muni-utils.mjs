// 6桁 = 都道府県2桁 + 市区町村3桁 + 検査数字1桁
// 検査数字: 上5桁に 6,5,4,3,2 を乗じた和を11で割った剰余を11から引き、その一の位。

/** @param {string} base5 上5桁 @returns {number} 検査数字 */
export function checkDigit(base5) {
  if (!/^\d{5}$/.test(base5)) throw new Error(`invalid base5: ${base5}`);
  const w = [6, 5, 4, 3, 2];
  const sum = [...base5].reduce((acc, ch, i) => acc + Number(ch) * w[i], 0);
  return (11 - (sum % 11)) % 10;
}

/** @param {string} code6 @returns {boolean} */
export function isValidCode(code6) {
  if (!/^\d{6}$/.test(code6)) return false;
  return checkDigit(code6.slice(0, 5)) === Number(code6[5]);
}

